function norm(s: string): string {
  return s
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ")
    .replace(/\s*\/\s*/g, "/")
    .replace(/[()]/g, "");
}

/**
 * Nhãn tiếng Việt cho tên thuộc tính; không khớp → trả nguyên tên sàn.
 * Tên có sẵn dấu tiếng Việt → giữ nguyên (sàn đã dịch rồi).
 */
export function viAttributeName(name: string): string {
  if (!name) return name;
  if (/[À-ỹ]/.test(name)) return name;
  const key = norm(name);
  const hit = DICT[key];
  if (hit) return hit;
  // "Material (Outer)" / "Color - Main": thử phần trước ngoặc / gạch.
  const head = norm(name.split(/[(\-–:]/)[0] ?? "");
  if (head && head !== key && DICT[head]) return `${DICT[head]} (${name.trim()})`;
  return name;
}
